// 1을 콘솔에 출력합니다.
console.log(1);

// setTimeout 함수를 호출하여 3초 후에 콜백 함수를 실행하도록 Web API에 요청합니다.
// setTimeout는 Web API의 일부로, 브라우저가 타이머를 설정하고 시간이 지난 후 콜백 함수를 실행합니다.
setTimeout(() => {
  console.log(2);
}, 3000);
// Web API에 setTimeout을 위탁하면서 콜백 함수도 같이 넘겨줍니다.
// 3초 후에 콜백 함수가 실행되어 2를 콘솔에 출력합니다.

console.log(3);
// 3을 콘솔에 출력합니다.
// 이 시점에서 1과 3이 즉시 출력됩니다. 
// 3초가 지나면 Web API가 콜백 함수를 호출하여 2가 출력됩니다.

// 따라서, 출력 순서는 다음과 같습니다:
// 1
// 3
// (3초 후)
// 2

// setTimeout은 비동기적으로 코드가 실행되도록 설정할 수 있습니다.
// 즉, 메인 스레드는 setTimeout을 호출한 후에도 계속해서 실행됩니다.
// 콜백 함수는 지정된 시간이 지난 후에 실행됩니다.
